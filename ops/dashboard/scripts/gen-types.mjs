// Generates src/api/types.ts from ../../contracts/jsonschema/*.json (read-only; nothing is written to contracts/).
// Every schema file carries its own $defs. They are hoisted into one root so shared enums (Priority, Lang, ...) are
// declared once. Conflicting definitions with the same name abort the run.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = resolve(here, "../../../contracts/jsonschema");
const outFile = resolve(here, "../src/api/types.ts");

const canon = (v) =>
  JSON.stringify(v, (_k, x) =>
    x && typeof x === "object" && !Array.isArray(x)
      ? Object.fromEntries(Object.entries(x).sort(([a], [b]) => a.localeCompare(b)))
      : x,
  );

// pydantic puts a "title" on every property; json-schema-to-typescript turns each into a named alias (CreatedAt1, ...).
// Drop titles below the definition level so properties are inlined and definitions keep their own names.
function stripTitles(node) {
  if (Array.isArray(node)) return node.map(stripTitles);
  if (node && typeof node === "object") {
    const out = {};
    for (const [k, v] of Object.entries(node)) {
      if (k === "title" && typeof v === "string") continue;
      out[k] = k === "properties" || k === "$defs" ? mapValues(v) : stripTitles(v);
    }
    return out;
  }
  return node;
}
function mapValues(obj) {
  return Object.fromEntries(Object.entries(obj).map(([k, v]) => [k, stripTitles(v)]));
}

const defs = {};
const props = {};
for (const file of readdirSync(schemaDir).filter((f) => f.endsWith(".json")).sort()) {
  const schema = JSON.parse(readFileSync(join(schemaDir, file), "utf-8"));
  const name = file.replace(/\.json$/, "");
  const { $defs = {}, $schema, $id, ...rest0 } = schema;
  const rest = stripTitles(rest0);
  for (const [key, value0] of Object.entries($defs)) {
    const value = { title: key, ...stripTitles(value0) };
    if (key in defs && canon(defs[key]) !== canon(value)) {
      throw new Error(`Conflicting $defs "${key}" in ${file}`);
    }
    defs[key] = value;
  }
  if (defs[name] && canon({ title: name, ...rest }) !== canon(defs[name])) {
    throw new Error(`Schema ${name} collides with a $defs entry`);
  }
  defs[name] = { title: name, ...rest };
  props[name] = { $ref: `#/$defs/${name}` };
}

const root = {
  title: "ContractSchemas",
  type: "object",
  additionalProperties: false,
  properties: props,
  $defs: defs,
};

const banner =
  "/* eslint-disable */\n/**\n * GENERATED by `npm run gen:types` from contracts/jsonschema/*.json. DO NOT EDIT BY HAND.\n */";
const ts = await compile(root, "ContractSchemas", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  style: { singleQuote: false, semi: true },
});
mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, ts, "utf-8");
console.log(`wrote ${outFile} (${Object.keys(props).length} schemas)`);
